//! tupleboard — пространство кортежей с арендами: доска для агентов, а не прямые вызовы.
//!
//! Идея из архива музея потерянных идей, запись `linda` (Linda, Йель, 1986; JavaSpaces/Jini):
//! производитель кладёт данные, потребитель ищет их по шаблону, процессы развязаны по времени
//! и по месту. Аренды — лекарство от «агент упал — задача потерялась»: взял и умер, задача
//! вернулась в пространство сама.
//!
//! * [`space`] — пространство: шаблоны, аренды, TTL, ёмкость, снимок в JSON;
//! * [`server`] — HTTP-API поверх пространства (JSON, только std).
//! * [`team`] — командный слой: гейт доказательства, аудит (S3*), эскалация (S5), алгедоника.

pub mod server;
pub mod space;
pub mod team;

pub use space::{BadPattern, Space, SpaceFull, Stats};
